"""UY-026.2: lock the UY DQ job's dependencies for Glue 5.0 (Python 3.11, manylinux).

pip-compile resolves for the Python that runs it, and the repo runs 3.12. pip itself can
resolve for another target: ``pip install --dry-run --report`` with ``--python-version`` and
``--platform`` picks exactly the wheels Glue would install, and the report carries each one's
SHA-256. This turns that report into two hashed locks (see requirements/uy-dq.txt):

    requirements/uy-dq.lock            what goes into the .gluewheels.zip
    requirements/uy-dq-glue-base.lock  what Glue 5.0 already has, for CI to stand in for it

Like ``pip-compile`` without ``--upgrade``, the pins already in both locks are kept as long
as they still satisfy the input, so re-running is a no-op and CI can check the lock is in
sync. ``--upgrade`` lets them move.

    python scripts/uy_dq_lock.py
    python scripts/uy_dq_lock.py --upgrade
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
REQUIREMENTS = REPO / "requirements"
INPUT = REQUIREMENTS / "uy-dq.txt"
BASE = REQUIREMENTS / "glue-5.0-base.txt"
LOCK = REQUIREMENTS / "uy-dq.lock"
BASE_LOCK = REQUIREMENTS / "uy-dq-glue-base.lock"

#: Glue 5.0's target (Appendix B of the Glue docs). build_uy_dq_package.sh uses the same.
PYTHON_VERSION = "3.11"
PLATFORMS = ("manylinux2014_x86_64", "manylinux_2_28_x86_64", "manylinux_2_34_x86_64")

_PIN = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)==(\S+)")


def canonical(name: str) -> str:
    """PEP 503: ``PyYAML`` and ``ruamel.yaml`` become ``pyyaml`` and ``ruamel-yaml``."""
    return re.sub(r"[-_.]+", "-", name).lower()


def pins(text: str) -> dict[str, str]:
    """``name==version`` lines of a requirements or lock file, by canonical name."""
    out = {}
    for line in text.splitlines():
        match = _PIN.match(line.strip())
        if match:
            out[canonical(match.group(1))] = match.group(2)
    return out


def resolved(report: dict) -> dict[str, tuple[str, str]]:
    """Canonical name -> (version, sha256) of every wheel in a ``pip --report``."""
    out = {}
    for item in report["install"]:
        archive = item["download_info"].get("archive_info", {})
        sha = archive.get("hashes", {}).get("sha256")
        if not sha:
            raise SystemExit(f"no sha256 for {item['metadata']['name']} in pip's report")
        out[canonical(item["metadata"]["name"])] = (item["metadata"]["version"], sha)
    return out


def render(packages: dict[str, tuple[str, str]], what: str) -> str:
    lines = [
        "# Generated by scripts/uy_dq_lock.py from requirements/uy-dq.txt; do not edit.",
        f"# {what}",
        f"# Target: Python {PYTHON_VERSION}, {', '.join(PLATFORMS)} (AWS Glue 5.0).",
    ]
    for name in sorted(packages):
        version, sha = packages[name]
        lines += [f"{name}=={version} \\", f"    --hash=sha256:{sha}"]
    return "\n".join(lines) + "\n"


def split(
    packages: dict[str, tuple[str, str]], base: dict[str, str]
) -> tuple[dict[str, tuple[str, str]], dict[str, tuple[str, str]]]:
    """(for the zip, already in Glue). A Glue module at another version is an error."""
    ship, provided = {}, {}
    for name, (version, sha) in packages.items():
        if name not in base:
            ship[name] = (version, sha)
        elif base[name] == version:
            provided[name] = (version, sha)
        else:
            raise SystemExit(f"{name} resolved to {version}, but Glue 5.0 has {base[name]}")
    return ship, provided


def resolve(upgrade: bool) -> dict:
    with tempfile.TemporaryDirectory() as tmp:
        constraints = [f"-c {BASE}"]
        if not upgrade:
            kept = {}
            for lock in (LOCK, BASE_LOCK):
                if lock.exists():
                    kept |= pins(lock.read_text(encoding="utf-8"))
            constraints += [f"{name}=={version}" for name, version in sorted(kept.items())]
        keep = Path(tmp) / "constraints.txt"
        keep.write_text("\n".join(constraints) + "\n", encoding="utf-8")
        report = Path(tmp) / "report.json"
        command = [
            sys.executable, "-m", "pip", "install", "--dry-run", "--ignore-installed",
            "--quiet", "--disable-pip-version-check", "--report", str(report),
            "--only-binary=:all:", "--python-version", PYTHON_VERSION, "--implementation", "cp",
            *(arg for p in PLATFORMS for arg in ("--platform", p)),
            "-r", str(INPUT), "-c", str(keep),
        ]  # fmt: skip
        subprocess.run(command, check=True)
        return json.loads(report.read_text(encoding="utf-8"))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--upgrade", action="store_true", help="let the pins move")
    args = parser.parse_args(argv)

    base = pins(BASE.read_text(encoding="utf-8"))
    ship, provided = split(resolved(resolve(args.upgrade)), base)
    LOCK.write_text(render(ship, "Goes into the .gluewheels.zip."), encoding="utf-8")
    BASE_LOCK.write_text(
        render(provided, "Already in Glue 5.0: CI installs it to stand in for Glue."),
        encoding="utf-8",
    )
    print(f"{LOCK.name}: {len(ship)} packages; {BASE_LOCK.name}: {len(provided)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
